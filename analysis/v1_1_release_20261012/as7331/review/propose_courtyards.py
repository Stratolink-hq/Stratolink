#!/usr/bin/env python3
"""Explicitly targeted courtyard proposal; run only on a disposable CAD copy.

No copper, pad, paste, model, or body graphics are altered. Optional R27 move
requires its routing to be regenerated by the CAD owner after application.
"""
import argparse, hashlib, importlib.util, json, math, uuid
from pathlib import Path
HERE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('m',HERE.parents[1]/'identities/build_metadata.py')
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
a=m.a
NS=uuid.UUID('b460574b-a52d-45c8-ac7d-ead57f7dd5da')

def direct(text,kind=None):
    return [(s,e,text[s:e],a.parse(text[s:e])) for s,e,d in m.m.spans(text)
            if d==1 and (kind is None or text[s:e].split(None,1)[0]=='('+kind)]

def geometry(ref):
    if ref=='U5':
        # TI max package outline 0.98 x 1.518 mm plus 0.25 mm on each side.
        p=[(-.74,-1.009),(.74,-1.009),(.74,1.009),(-.74,1.009)]
    else:
        # 0805 pads: centers +/-0.9125, size 1.025x1.4, radius 0.25.
        # Exact pad/max-body envelope +0.125 mm is inside this octagon.
        # The originally suggested .22 chamfer misses the offset roundrect
        # by 0.000235 mm; .21 is a conservative containing approximation.
        p=[(-1.55,-.615),(-1.34,-.825),(1.34,-.825),(1.55,-.615),
           (1.55,.615),(1.34,.825),(-1.34,.825),(-1.55,.615)]
    return '\n'.join('(fp_line (start %.6f %.6f) (end %.6f %.6f) '
       '(stroke (width 0.05) (type solid)) (layer "F.CrtYd") (uuid "%s"))'
       %(*p[i],*p[(i+1)%len(p)],uuid.uuid5(NS,ref+str(i))) for i in range(len(p)))

def patch_footprint(text,ref,move_y=None):
    edits=[]
    for s,e,block,n in direct(text):
        if n[0].startswith('fp_') and a.scalar(n,'layer')=='F.CrtYd':edits.append((s,e,''))
        if ref=='R27' and n[0]=='at' and move_y is not None:
            assert [float(v) for v in n[1:]] in [[71.9,34.3,90.0],[71.9,34.08,90.0]]
            edits.append((s,e,f'(at 71.9 {move_y:.6f} 90)'))
    out=m.m.replace(text,edits)
    return out[:-1]+'\n'+geometry(ref)+'\n)'

def without_target_metadata(n,ref,is_board):
    return [x for x in n if not (isinstance(x,list) and (
       (x[0].startswith('fp_') and a.scalar(x,'layer')=='F.CrtYd') or
       (ref=='R27' and is_board and x[0]=='at')))]

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--project',type=Path,required=True)
    ap.add_argument('--r27-y',type=float,choices=[34.3,34.08],default=34.08)
    q=ap.parse_args(); assert q.project.resolve()!=HERE.parents[3]/'hardware/pcb'
    pcb=q.project/'stratolink.kicad_pcb';before=pcb.read_text();edits=[];records={}
    for s,e,block,n in direct(before,'footprint'):
        ref=a.prop(n,'Reference')
        if ref not in ['U5','R27']:continue
        new=patch_footprint(block,ref,q.r27_y if ref=='R27' else None)
        assert without_target_metadata(n,ref,True)==without_target_metadata(a.parse(new),ref,True)
        edits.append((s,e,new))
        lib=q.project/'lib'/(n[1].split(':')[-1]+'.kicad_mod');oldlib=lib.read_text()
        newlib=patch_footprint(oldlib.rstrip(),ref)
        assert without_target_metadata(a.parse(oldlib),ref,False)==without_target_metadata(a.parse(newlib),ref,False)
        lib.write_text(newlib+'\n')
        records[ref]=dict(library=str(lib),before_library_sha256=hashlib.sha256(oldlib.encode()).hexdigest(),after_library_sha256=hashlib.sha256(lib.read_bytes()).hexdigest())
    assert set(records)=={'U5','R27'}
    pcb.write_text(m.m.replace(before,edits))
    # Support-function check of the exact rounded-pad offset at diagonal edge.
    radius=.25+.125;center_sum=(.9125+1.025/2-.25)+(1.4/2-.25)
    clearance=(1.55+.825-.21-center_sum)/math.sqrt(2)-.25
    assert clearance>=.125
    records.update(pcb_before_sha256=hashlib.sha256(before.encode()).hexdigest(),pcb_after_sha256=hashlib.sha256(pcb.read_bytes()).hexdigest(),r27_y_mm=q.r27_y,r27_diagonal_min_pad_clearance_mm=clearance,u5_max_body_margin_mm=.25,changes='U5/R27 courtyard metadata and optional explicit R27 position only; routed copy must be rerouted before release.')
    (q.project/'courtyard-proposal.json').write_text(json.dumps(records,indent=2)+'\n')
    print(json.dumps(records,indent=2))
if __name__=='__main__':main()
