#!/usr/bin/env python3
"""Generate photo-scaled ZachTek solar assemblies for the KiCad 3D viewer.

All construction coordinates are millimetres relative to the notch centre:
x right, y down the board, z toward the PCB front; z=0 is board midplane.
VRML uses KiCad's 2.54 mm units and opposite y. No electrical CAD is edited.
"""
from pathlib import Path
import json
import math

HERE = Path(__file__).resolve().parent
LENGTH = 94.0  # Metric-grid photograph: 94 +/- 2 mm, not a vendor tolerance.
WIDTH = 75.0  # Metric-grid photograph: 75 +/- 1.5 mm.
THICKNESS = 0.20  # Display assumption; film thickness is not resolved by the photo.
INSERTION = 1.5  # Straight bank of the 2 mm deep, R0.5 notch.
STRAIGHT = 7.0  # Keep the complete photographed terminal strip unbent.
RADIUS = 140.0  # Assembly choice, not a supplier-approved minimum bend radius.
TERMINAL = 5.0  # Photo nominal; visible band is approximately 4--6.5 mm.
METAL_OFFSET = 0.028
WIRE_DIAMETER = 0.50
INSULATION_DIAMETER = 0.70

MATERIALS = {
    'film': ((0.18, 0.14, 0.09), 0.25),
    'cell': ((0.055, 0.067, 0.075), 0.52),
    'bus': ((0.63, 0.65, 0.62), 0.70),
    'solder': ((0.73, 0.75, 0.77), 0.78),
    'wire': ((0.76, 0.23, 0.07), 0.55),
    'red': ((0.73, 0.035, 0.025), 0.30),
    'mark': ((0.91, 0.90, 0.81), 0.10),
}


def add(a, b):
    return tuple(x + y for x, y in zip(a, b))


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def mul(a, k):
    return tuple(x * k for x in a)


def cross(a, b):
    return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])


def unit(a):
    return mul(a, 1 / math.sqrt(sum(x*x for x in a)))


class Model:
    def __init__(self):
        self.parts = []

    def mesh(self, name, vertices, faces, material):
        self.parts.append((name, vertices, faces, material))

    def tube(self, name, points, radius, material, sides=12):
        vertices = []
        for i, point in enumerate(points):
            tangent = unit(sub(points[min(i+1, len(points)-1)], points[max(i-1, 0)]))
            axis = (0, 0, 1) if abs(tangent[2]) < 0.9 else (0, 1, 0)
            u = unit(cross(tangent, axis))
            v = cross(tangent, u)
            for j in range(sides):
                angle = 2*math.pi*j/sides
                vertices.append(add(point, mul(add(mul(u, math.cos(angle)), mul(v, math.sin(angle))), radius)))
        faces = []
        for i in range(len(points)-1):
            for j in range(sides):
                faces.append((i*sides+j, i*sides+(j+1)%sides, (i+1)*sides+(j+1)%sides, (i+1)*sides+j))
        faces.extend([tuple(range(sides-1, -1, -1)), tuple((len(points)-1)*sides+j for j in range(sides))])
        self.mesh(name, vertices, faces, material)

    def write(self, path):
        text = ['#VRML V2.0 utf8', '# Photo-scaled assembly, NOT a vendor dimensional model.',
                '# Generated by generate.py; one VRML unit = 2.54 mm in KiCad.']
        for name, vertices, faces, material in self.parts:
            color, shine = MATERIALS[material]
            coords = ',\n'.join(' '.join(f'{q:.7f}' for q in (x/2.54, -y/2.54, z/2.54)) for x,y,z in vertices)
            indices = ',\n'.join(' '.join(map(str, face))+' -1' for face in faces)
            text.append(f'# {name}\nShape {{\n appearance Appearance {{ material Material {{ diffuseColor {color[0]} {color[1]} {color[2]} specularColor 0.45 0.45 0.45 shininess {shine} }} }}\n geometry IndexedFaceSet {{ solid FALSE creaseAngle 0.7 coord Coordinate {{ point [\n{coords}\n] }} coordIndex [\n{indices}\n] }}\n}}')
        path.write_text('\n'.join(text)+'\n')


def panel_point(sign, s, z, depth=0):
    """Constant-radius bend after a straight terminal. depth points into film."""
    angle = max(0, s-STRAIGHT)/RADIUS
    x = min(s, STRAIGHT) + RADIUS*math.sin(angle) - INSERTION
    # Seat the exposed terminal metal, rather than burying it in the FR4 bank.
    y = -0.5 + METAL_OFFSET + RADIUS*(1-math.cos(angle))
    return (sign*(x-depth*math.sin(angle)), y+depth*math.cos(angle), z)


def ribbon(model, sign, name, start, stop, z0, z1, depth, material, closed=False):
    count = max(1, math.ceil((stop-start)/0.75))
    stations = [start+(stop-start)*i/count for i in range(count+1)]
    vertices = [panel_point(sign, s, z, depth) for s in stations for z in (z0,z1)]
    faces = [(2*i, 2*i+1, 2*i+3, 2*i+2) for i in range(count)]
    if closed:
        n = len(vertices)
        vertices += [panel_point(sign, s, z, THICKNESS) for s in stations for z in (z0,z1)]
        faces += [tuple(n+j for j in reversed(face)) for face in list(faces)]
        faces += [(2*i,2*i+2,n+2*i+2,n+2*i) for i in range(count)]
        faces += [(2*i+1,n+2*i+1,n+2*i+3,2*i+3) for i in range(count)]
        faces += [(0,n,n+1,1),(n-2,n-1,2*n-1,2*n-2)]
    if sign < 0:
        faces = [tuple(reversed(face)) for face in faces]
    model.mesh(name, vertices, faces, material)


def bezier(points, count=48):
    a,b,c,d = points
    return [tuple((1-t)**3*a[j]+3*(1-t)**2*t*b[j]+3*(1-t)*t*t*c[j]+t**3*d[j] for j in range(3))
            for t in (i/count for i in range(count+1))]


def build(sign, positive_x):
    model = Model()
    ribbon(model,sign,'polymer laminate',0,LENGTH,-WIDTH/2,WIDTH/2,0,'film',closed=True)
    # Four groups of five fingers reproduce the photograph's appearance only.
    for i in range(20):
        z0 = -WIDTH/2+0.8+i*(WIDTH-1.6)/20
        gap = .40 if i % 5 == 4 else .12
        z1 = z0+(WIDTH-1.6)/20-gap
        ribbon(model,sign,f'cosmetic cell finger {i+1}',TERMINAL,LENGTH-TERMINAL,z0,z1,-0.015,'cell')
    ribbon(model,sign,'inner NEGATIVE terminal',0,TERMINAL,-WIDTH/2,WIDTH/2,-METAL_OFFSET,'bus')
    ribbon(model,sign,'outer POSITIVE terminal',LENGTH-TERMINAL,LENGTH,-WIDTH/2,WIDTH/2,-METAL_OFFSET,'bus')
    # Visible minus at the inner strip and plus at the outer strip.
    for s,positive in [(1.7,False),(LENGTH-1.5,True)]:
        z = 9.0
        model.tube('polarity minus', [panel_point(sign,s,z-1,-.08),panel_point(sign,s,z+1,-.08)],.13,'mark')
        if positive:
            model.tube('polarity plus',[panel_point(sign,s-1,z,-.08),panel_point(sign,s+1,z,-.08)],.13,'mark')
    # Front and rear triangular fillets wet the same upper terminal face and GND land.
    for face in [-1,1]:
        triangle = [(-.5,face*.2),(-1.20,face*.2),(-.5,face*.80)]
        vertices = [(sign*x,y,z) for x in [-1.45,-.25] for y,z in triangle]
        model.mesh('ground solder fillet '+('front' if face>0 else 'rear'),vertices,
                   [(0,1,2),(3,5,4),(0,3,4,1),(1,4,5,2),(2,5,3,0)],'solder')
    # Central positive contact: follow the exposed face beyond the free edge,
    # then turn under it. An immediate inward/downward return would pierce film.
    tip = panel_point(sign,LENGTH-TERMINAL/2,0,-.32)
    edge = panel_point(sign,LENGTH+1.0,0,-.32)
    below = panel_point(sign,LENGTH+1.0,0,1.0)
    hook = bezier([edge,add(edge,(sign*.8,.8,0)),add(below,(sign*.8,0,0)),below],16)
    knee = (positive_x+sign*1.2,30.5,1.0)
    through = (positive_x,30.5,.20)
    inner = bezier([knee,(positive_x,30.5,1.0),(positive_x,30.5,.7),through],16)
    wire_path = [tip,edge] + hook[1:] + [knee] + inner[1:] + [(positive_x,30.5,-.80)]
    model.tube('positive copper lead',wire_path,WIRE_DIAMETER/2,'wire')
    # Bare ends remain visible where soldered; sleeve stops before through-hole.
    model.tube('positive red insulation',[below,knee]+inner[1:9],INSULATION_DIAMETER/2,'red')
    # Solder beads at outer terminal and PCB hole are illustrative menisci.
    model.tube('panel positive solder',[add(tip,(0,0,-.65)),add(tip,(0,0,.65))],.40,'solder')
    for z in [-.27,.27]:
        ring=[(positive_x+.42*math.cos(2*math.pi*i/32),30.5+.42*math.sin(2*math.pi*i/32),z) for i in range(33)]
        model.tube('positive PTH solder',ring,.16,'solder',8)
    length = sum(math.dist(a,b) for a,b in zip(wire_path,wire_path[1:]))
    return model, {'positive_pad_local_mm':[positive_x,30.5,0], 'panel_tip_local_mm':list(tip),
                   'wire_centreline_length_mm':length, 'root_face_y_mm':-.5,
                   'root_insertion_mm':INSERTION,
                   'wire_hook_clears_outer_edge_mm':1.0,
                   'wire_long_chord_mm':math.dist(below,knee), 'parts':len(model.parts)}


def main():
    report = {'purpose':'Photo-scaled KiCad assembly; not a physical strength qualification or vendor model',
              'dimensions_are_estimated':True,
              'source':'qualification/metrology relative to analysis/v1_1_solar_attachments_20261012',
              'photo_length_uncertainty_mm':2.0,'photo_width_uncertainty_mm':1.5,
              'unverified_dimensions':['film thickness','prepared terminal thickness','wettable area','bend radius limit'],
              'developed_panel_length_mm':LENGTH,
              'panel_width_mm':WIDTH,'film_thickness_mm':THICKNESS,'straight_root_length_mm':STRAIGHT,
              'bend_radius_mm':RADIUS,'terminal_width_mm':TERMINAL,
              'wire_conductor_diameter_mm':WIRE_DIAMETER,'wire_outer_diameter_mm':INSULATION_DIAMETER,
              'model_offset_z_mm':-.2,'sides':{}}
    for side,sign,x in [('left',-1,54.8-53.3165),('right',1,75.2-76.6755)]:
        model,details=build(sign,x)
        model.write(HERE/f'zachtek_1044_{side}_assembly.wrl')
        report['sides'][side]=details
    (HERE/'geometry.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))


if __name__=='__main__':
    main()
